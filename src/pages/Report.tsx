// Print-ready client report (Save as PDF from the browser). Branded with the
// workspace's logo and color. Route: /report?board=ID  or  /report?share=TOKEN
import { useEffect, useState } from "react";
import { Download, Printer } from "lucide-react";
import { CATALOG_BY_TYPE } from "../../shared/catalog";
import { simulate } from "../../shared/simulate";
import { funnelSvg } from "../components/FunnelSvg";
import { api, type Analysis, type Branding, type Metrics } from "../lib/api";
import { num, pct, usd } from "../lib/format";
import type { BoardRecord } from "../lib/store";

export function Report() {
  const q = new URLSearchParams(location.search);
  const [board, setBoard] = useState<(BoardRecord & { branding?: Branding | null }) | null>(null);
  const [branding, setBranding] = useState<Branding | null>(null);
  const [metrics, setMetrics] = useState<Metrics | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    (async () => {
      try {
        if (q.get("share")) {
          const b = await api.shared(q.get("share")!);
          setBoard(b);
          setBranding(b.branding ?? null);
        } else {
          const id = q.get("board")!;
          const [b, me] = await Promise.all([api.getBoard(id), api.me()]);
          setBoard(b);
          setBranding({ name: me.workspace.name, ...(me.workspace.branding ?? {}) });
          const to = new Date().toISOString().slice(0, 10);
          const from = new Date(Date.now() - 29 * 86400e3).toISOString().slice(0, 10);
          setMetrics(await api.metrics(id, from, to).catch(() => null));
        }
      } catch (e) {
        setError((e as Error).message);
      }
    })();
  }, []);

  if (error) return <div className="report-page"><div className="error">{error}</div></div>;
  if (!board) return <div className="boot"><span className="spinner" /></div>;

  const sim = simulate(board.graph);
  const t = sim.totals;
  const analysis = board.analysis as Analysis | null;
  const accent = branding?.color ?? "#6d5efc";
  const steps = board.graph.nodes.filter((n) => n.data.kind !== "note" && n.data.kind !== "integration");
  const tools = board.graph.nodes.filter((n) => n.data.kind === "integration");
  const m = metrics && metrics.days.length ? metrics : null;

  return (
    <div className="report-page" style={{ "--accent": accent } as React.CSSProperties}>
      <div className="report-actions no-print">
        <button className="btn primary" onClick={() => window.print()}>
          <Download size={15} /> Download PDF
        </button>
        <button className="btn" onClick={() => window.print()}>
          <Printer size={15} /> Print
        </button>
        <span className="muted small">Tip: choose “Save as PDF” as the destination.</span>
      </div>

      <header className="report-cover">
        {branding?.logo && <img src={branding.logo} alt="" className="report-logo" />}
        <div className="report-brand">{branding?.name}</div>
        <h1>{board.name}</h1>
        <p>Campaign plan &amp; performance report · {new Date().toLocaleDateString("en-US", { dateStyle: "long" })}</p>
      </header>

      {board.summary && (
        <section>
          <h2>Strategy</h2>
          <p className="lead">{board.summary}</p>
        </section>
      )}

      <section>
        <h2>Monthly forecast</h2>
        <div className="report-kpis">
          {[
            ["Ad spend", usd(t.spend)],
            ["Visitors", num(t.visitors)],
            ["Leads", num(t.leads)],
            ["Customers", num(t.customers)],
            ["Revenue", usd(t.revenue)],
            ["ROAS", `${t.roas.toFixed(2)}x`],
            ["Cost per customer", t.customers ? usd(t.cpa) : "—"],
            ["Profit", usd(t.profit)],
          ].map(([k, v]) => (
            <div key={k}>
              <span>{k}</span>
              <b>{v}</b>
            </div>
          ))}
        </div>
      </section>

      <section className="avoid-break">
        <h2>Funnel</h2>
        {/* Generated by funnelSvg with escaped labels. */}
        <div className="report-funnel" dangerouslySetInnerHTML={{ __html: funnelSvg(board.graph, sim, { accent }) }} />
      </section>

      {m && (
        <section className="avoid-break">
          <h2>Performance — last 30 days</h2>
          <div className="report-kpis">
            {[
              ["Spend", usd(m.totals.spend)],
              ["Revenue", usd(m.totals.revenue)],
              ["ROAS", m.totals.spend ? `${(m.totals.revenue / m.totals.spend).toFixed(2)}x` : "—"],
              ["Conversions", num(m.totals.conversions)],
            ].map(([k, v]) => (
              <div key={k}>
                <span>{k}</span>
                <b>{v}</b>
              </div>
            ))}
          </div>
        </section>
      )}

      <section>
        <h2>Plan by step</h2>
        <table className="report-table">
          <thead>
            <tr>
              <th>Step</th>
              <th>Type</th>
              <th>Assumption</th>
              <th>Forecast</th>
              <th>Actual (this month)</th>
            </tr>
          </thead>
          <tbody>
            {steps.map((n) => {
              const r = sim.nodes[n.id];
              const d = n.data;
              const a = d.actuals;
              return (
                <tr key={n.id}>
                  <td>{d.label}</td>
                  <td>{CATALOG_BY_TYPE[d.type]?.label}</td>
                  <td>{d.kind === "traffic" ? (d.budget ? `${usd(d.budget)}/mo · $${d.cpc ?? "—"} CPC` : `${num(d.visitors)} visitors`) : `${pct(d.conversionRate, 0)} continue${d.price ? ` · ${usd(d.price)}` : ""}`}</td>
                  <td>{r ? `${num(r.inflow)} → ${num(r.outflow)}${r.revenue ? ` · ${usd(r.revenue)}` : ""}` : "—"}</td>
                  <td>{a && Object.values(a).some((v) => v != null) ? [a.spend != null && usd(a.spend), a.clicks != null && `${num(a.clicks)} clicks`, a.conversions != null && `${num(a.conversions)} conv.`].filter(Boolean).join(" · ") : "—"}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
        {!!tools.length && <p className="muted small">Tools &amp; tracking: {tools.map((n) => n.data.label).join(", ")}</p>}
      </section>

      {analysis && (
        <section>
          <h2>Findings · health score {Math.round(analysis.healthScore)}/100</h2>
          <p className="lead">{analysis.headline}</p>
          {analysis.findings.map((f, i) => (
            <div key={i} className={`report-finding sev-${f.severity}`}>
              <b>{f.title}</b>
              <p>{f.detail}</p>
              <p>
                <b>Recommendation:</b> {f.recommendation}
              </p>
            </div>
          ))}
          {!!analysis.experiments.length && (
            <>
              <h3>Experiments to run next</h3>
              <ol>
                {analysis.experiments.map((x, i) => (
                  <li key={i}>
                    <b>{x.hypothesis}</b> — {x.test} <i>({x.expectedImpact})</i>
                  </li>
                ))}
              </ol>
            </>
          )}
        </section>
      )}

      {!branding?.hidePoweredBy && <footer className="report-foot">Made with AdCanvas</footer>}
    </div>
  );
}
