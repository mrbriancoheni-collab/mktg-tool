// Extracts only the simple-icons logos referenced by the catalog into a small
// generated module, so the client bundle doesn't ship all ~3,000 icons.
import fs from "node:fs";
import * as SI from "simple-icons";
import { CATALOG } from "../shared/catalog";

const bySlug = new Map(Object.values(SI as Record<string, { slug: string; path: string; hex: string; title: string }>).map((i) => [i.slug, i]));
const used = [...new Set(CATALOG.map((c) => c.brand).filter(Boolean))] as string[];
const out: Record<string, { path: string; hex: string; title: string }> = {};
for (const slug of used.sort()) {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  out[slug] = { path: icon.path, hex: icon.hex, title: icon.title };
}
fs.writeFileSync(
  "src/lib/brandIcons.generated.ts",
  `// Generated by scripts/gen-brand-icons.ts from simple-icons (CC0). Do not edit.\n` +
    `// Brand logos are trademarks of their respective owners.\n` +
    `export const BRAND_ICONS: Record<string, { path: string; hex: string; title: string }> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`Wrote ${used.length} brand icons`);

// Lucide: named imports only for icons the catalog uses, so the bundle stays small.
const lucide = [...new Set(["Circle", ...CATALOG.map((c) => c.icon)])].sort();
fs.writeFileSync(
  "src/lib/catalogIcons.generated.ts",
  `// Generated by scripts/gen-brand-icons.ts. Do not edit.\n` +
    `import type { LucideIcon } from "lucide-react";\n` +
    `import { ${lucide.join(", ")} } from "lucide-react";\n\n` +
    `export const CATALOG_ICONS: Record<string, LucideIcon> = { ${lucide.join(", ")} };\n`,
);
console.log(`Wrote ${lucide.length} lucide icons`);
